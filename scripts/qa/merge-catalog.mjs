/**
 * Merge every catalog.json found under qa/reports into the tracked
 * catalog `docs/qa/behaviors.json` and regenerate `docs/qa/behavior-catalog.md`.
 *
 * Records are keyed by id. The newest round wins for status/evidence, but one
 * behavior id must keep the same title across rounds; conflicts are reported.
 *
 * Usage: node scripts/qa/merge-catalog.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../lib/context.mjs';

const REPORTS = path.join(ROOT, 'qa/reports');
const OUT_JSON = path.join(ROOT, 'docs/qa/behaviors.json');
const OUT_MD = path.join(ROOT, 'docs/qa/behavior-catalog.md');

const AREA_TITLES = {
  visitor: 'A 访客浏览',
  interact: 'B 访客交互',
  media: 'C 媒体播放',
  mobile: 'D 移动端/无障碍/弱网',
  admin: 'E 后台',
  edge: 'F 边界/故障/安全',
  perf: 'G 性能/SEO',
};

function roundOf(directory) {
  const match = directory.match(/round-(\d+)/);
  return match ? Number(match[1]) : 0;
}

function listCatalogFiles(directory, found = []) {
  if (!fs.existsSync(directory)) return found;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) listCatalogFiles(full, found);
    else if (entry.name === 'catalog.json') found.push(full);
  }
  return found;
}

function normalise(record, source, round) {
  const id = String(record.id || '').trim();
  if (!id) return null;
  return {
    id,
    area: record.area || 'unknown',
    title: record.title || '',
    surface: record.surface || '',
    steps: Array.isArray(record.steps) ? record.steps : [],
    expected: record.expected || '',
    status: record.status || 'unknown',
    coveredBy: record.coveredBy || '',
    evidence: Array.isArray(record.evidence) ? record.evidence : [],
    round,
    source: path.relative(ROOT, source),
  };
}

function main() {
  const files = listCatalogFiles(REPORTS).sort();
  const merged = new Map();
  const conflicts = [];
  for (const file of files) {
    let records;
    try {
      records = JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch (error) {
      console.warn(`skip ${path.relative(ROOT, file)}: ${error.message}`);
      continue;
    }
    if (!Array.isArray(records)) records = records.behaviors || [];
    const round = roundOf(file);
    for (const raw of records) {
      const record = normalise(raw, file, round);
      if (!record) continue;
      const existing = merged.get(record.id);
      if (!existing) {
        merged.set(record.id, record);
        continue;
      }
      if (existing.title && record.title && existing.title !== record.title) {
        conflicts.push(`${record.id}: "${existing.title}" (${existing.source}) vs "${record.title}" (${record.source})`);
      }
      if (record.round >= existing.round) {
        merged.set(record.id, { ...existing, ...record, round: record.round });
      }
    }
  }

  const behaviors = [...merged.values()].sort((a, b) =>
    a.id.localeCompare(b.id, 'en', { numeric: true }),
  );
  fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
  fs.writeFileSync(OUT_JSON, JSON.stringify(behaviors, null, 2) + '\n');

  const byArea = new Map();
  for (const record of behaviors) {
    if (!byArea.has(record.area)) byArea.set(record.area, []);
    byArea.get(record.area).push(record);
  }
  const statusCounts = behaviors.reduce((acc, record) => {
    acc[record.status] = (acc[record.status] || 0) + 1;
    return acc;
  }, {});
  const lines = [
    '# Mosaic behavior catalog',
    '',
    `Generated by \`node scripts/qa/merge-catalog.mjs\` from ${files.length} catalog file(s).`,
    `Total behaviors: **${behaviors.length}** — ${Object.entries(statusCounts)
      .map(([status, count]) => `${status}: ${count}`)
      .join(', ')}.`,
    '',
    'Status meanings: `pass` = asserted and currently green; `fail` = asserted against',
    'correct behavior and currently failing (defect tracked); `partial` = only part of',
    'the journey is asserted; `manual` = verified by hand; `blocked` = needs a credential',
    'or environment we must not use; `unknown` = cataloged but not yet exercised.',
    '',
  ];
  for (const [area, records] of [...byArea.entries()].sort()) {
    lines.push(`## ${AREA_TITLES[area] || area} (${records.length})`, '');
    lines.push('| ID | Behavior | Steps | Expected | Status | Evidence |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const record of records) {
      const steps = record.steps.join(' → ').replace(/\|/g, '\\|');
      lines.push(
        `| ${record.id} | ${record.title.replace(/\|/g, '\\|')} | ${steps} | ${record.expected.replace(/\|/g, '\\|')} | ${record.status} | ${record.coveredBy || record.source} |`,
      );
    }
    lines.push('');
  }
  fs.writeFileSync(OUT_MD, lines.join('\n') + '\n');

  console.log(`merged ${behaviors.length} behaviors from ${files.length} files -> docs/qa/behaviors.json`);
  console.log(Object.entries(statusCounts).map(([status, count]) => `${status}=${count}`).join(' '));
  if (conflicts.length) {
    console.warn(`title conflicts (${conflicts.length}):`);
    for (const conflict of conflicts.slice(0, 20)) console.warn(`  ${conflict}`);
  }
}

main();
