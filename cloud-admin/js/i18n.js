export function t(path, vars = {}) {
  const lang = localStorage.getItem('mosaic_admin_lang') || 'zh-CN';
  let s = path.split('.').reduce((o, k) => (o || {})[k], I18N[lang]);
  if (s === undefined) s = path.split('.').reduce((o, k) => (o || {})[k], I18N['zh-CN']);
  if (s === undefined) s = path;
  for (const [k, v] of Object.entries(vars)) s = String(s).replace(`{${k}}`, v);
  return s;
}

let _onLangChange = null;
export function setLang(lang) {
  localStorage.setItem('mosaic_admin_lang', lang);
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  if (_onLangChange) _onLangChange(lang);
}
export function onLangChange(fn) {
  _onLangChange = fn;
}
